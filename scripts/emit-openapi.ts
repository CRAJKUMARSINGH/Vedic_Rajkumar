#!/usr/bin/env tsx
/**
 * emit-openapi.ts — regenerates docs/api/openapi.yaml from src/api/v1/openapi.ts
 * (zod-to-openapi). The hand-written yaml and the generated spec previously
 * disagreed by construction; now there is one spec and it is generated.
 *
 * Requires `tsx` (adds `@/` alias resolution that node --strip-types lacks).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { generateOpenApi } from '../src/api/v1/openapi';

const HEADER = '# @generated by scripts/emit-openapi.ts — do not hand-edit\n';
const OUT = resolve(process.cwd(), 'docs/api/openapi.yaml');

const doc = generateOpenApi();
const yaml = JSON.stringify(doc, null, 2); // swap for a yaml emitter if you prefer

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${HEADER}${yaml}\n`, 'utf-8');
console.log(`openapi:emitted ${OUT}`);
