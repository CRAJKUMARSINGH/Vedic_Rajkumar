#!/usr/bin/env node
/**
 * deploy-safety.mjs — pre-deploy gate. Runs BEFORE any production deploy.
 *
 * Six checks, each one a way a deploy has silently broken production:
 *   1. a destructive migration without an expand/contract plan
 *   2. MIN_CLIENT_VERSION raised while the previous client is still common
 *   3. a new surface with no feature flag (so no kill switch)
 *   4. a hand-written SW (injectManifest) with an unbumped cache version
 *   5. no rollback artefact (the previous deploy id)
 *   6. a secret referenced but absent from the vault manifest
 *
 * Usage: node scripts/deploy-safety.mjs [--production]
 */
import { execSync } from 'node:child_process';
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const PROD = process.argv.includes('--production');
const problems = [];
const notes = [];

const read = (p) => (existsSync(p) ? readFileSync(p, 'utf-8') : '');
const git = (cmd) => { try { return execSync(cmd, { encoding: 'utf-8' }).trim(); } catch { return ''; } };

/** Every .ts file under `dir`, concatenated. The secret scan needs the whole tree,
 *  and readdirSync on a file throws — so branch on the type instead of catching. */
const readTree = (dir) => {
  if (!existsSync(dir)) return '';
  if (!statSync(dir).isDirectory()) return read(dir);
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((e) =>
      e.isDirectory() ? [readTree(join(dir, e.name))] : e.name.endsWith('.ts') ? [read(join(dir, e.name))] : [],
    )
    .join('\n');
};

// ── 1. destructive migrations ────────────────────────────────────────────────
const migDir = join(ROOT, 'supabase', 'migrations');
if (existsSync(migDir)) {
  const pending = git('git diff --name-only HEAD~1 HEAD -- supabase/migrations').split('\n').filter(Boolean);
  const destructive = /drop\s+(table|column|schema)|alter\s+column\s+\w+\s+type|set\s+not\s+null/i;
  for (const f of pending) {
    const sql = read(join(ROOT, f));
    if (destructive.test(sql)) {
      const hasGuard = /if\s+exists|--\s*expand|--\s*contract|backfill/i.test(sql);
      if (!hasGuard) {
        problems.push(
          `${f}: destructive statement without an expand/contract marker.\n` +
          `     A one-step DROP breaks the OLD client which is still live. See docs/ops/UPDATE_SAFETY.md §2.`,
        );
      } else {
        notes.push(`${f}: destructive but guarded`);
      }
    }
  }
  if (!pending.length) notes.push('no new migrations');
}

// ── 2. client version floor ──────────────────────────────────────────────────
const cvPath = join(ROOT, 'supabase', 'functions', '_shared', 'client-version.ts');
const cv = read(cvPath);
const floor = cv.match(/MIN_CLIENT_VERSION\s*=\s*'([\d.]+)'/)?.[1];
const floorChanged = git(`git diff HEAD~1 HEAD -- ${cvPath}`).includes('MIN_CLIENT_VERSION');

if (floorChanged && floor) {
  const deployedAt = git('git log -1 --format=%ct -- src/lib/version.ts');
  if (deployedAt) {
    const days = (Date.now() / 1000 - Number(deployedAt)) / 86400;
    if (days < 7) {
      problems.push(
        `MIN_CLIENT_VERSION raised to ${floor} but the client that matches it is ${days.toFixed(1)} days old.\n` +
        `     Users on the previous version will get 426s. Wait 7 days or keep it lenient (hard: false).`,
      );
    }
  }
  notes.push(`client floor → ${floor}`);
}

// ── 3. new surface without a kill switch ─────────────────────────────────────
const flagManifest = join(ROOT, 'docs', 'flags.yaml');
const flags = read(flagManifest);
const newRoutes = git('git diff --name-only HEAD~1 HEAD -- src/pages').split('\n').filter(Boolean);
for (const f of newRoutes) {
  const name = f.replace(/.*\//, '').replace(/\.tsx?$/, '').toLowerCase();
  if (!flags.toLowerCase().includes(name) && newRoutes.length > 0) {
    problems.push(
      `new page ${f} has no entry in docs/flags.yaml.\n` +
      `     Without a flag, a bug there can only be fixed by a deploy. See runbooks/hotfix.md §3.`,
    );
  }
}

// ── 4. service worker cache version ──────────────────────────────────────────
// The SW is generated by vite-plugin-pwa. Under `generateSW` the precache
// manifest is revision-hashed per build, so stale-asset invalidation is
// build-derived — there is deliberately no public/sw.js to bump (a hand-written
// one is banned by scripts/check-duplicates.mjs). This check only has work to do
// if the strategy is ever switched to `injectManifest`, which hands us the SW.
const viteConfig = read(join(ROOT, 'vite.config.ts'));
const pwaStrategy = viteConfig.match(/strategies:\s*'([^']+)'/)?.[1];
const swPath = join(ROOT, 'public', 'sw.js');
const appVersion = read(join(ROOT, 'src', 'lib', 'version.ts')).match(/APP_VERSION\s*=\s*'([\d.]+)'/)?.[1];

if (pwaStrategy === 'generateSW') {
  notes.push(`sw cache: generateSW, precache revisions build-derived (client ${appVersion ?? 'unset'})`);
} else {
  const sw = read(swPath);
  if (!sw) {
    problems.push(
      `vite.config.ts uses strategies: '${pwaStrategy ?? 'unset'}' but public/sw.js does not exist.\n` +
      `     Nothing owns the cache version, so returning users can be served stale assets.\n` +
      `     See docs/ops/UPDATE_SAFETY.md §3.`,
    );
  } else {
    const cacheName = sw.match(/CACHE_VERSION\s*=\s*'([^']+)'/)?.[1];
    const assetsChanged = git('git diff --name-only HEAD~1 HEAD -- src').length > 0;
    const cacheBumped = git(`git diff HEAD~1 HEAD -- ${swPath}`).includes('CACHE_VERSION');
    if (assetsChanged && !cacheBumped) {
      problems.push(
        `assets changed but CACHE_VERSION (${cacheName ?? 'unset'}) was not bumped in public/sw.js.\n` +
        `     Returning users will serve stale assets against a fresh API.`,
      );
    } else if (cacheBumped) {
      notes.push(`sw cache → ${cacheName}`);
    }
  }
}

// ── 5. rollback artefact ─────────────────────────────────────────────────────
const rollbackFile = join(ROOT, '.deploy', 'rollback.json');
if (PROD && !existsSync(rollbackFile)) {
  notes.push('no .deploy/rollback.json — first production deploy, capture it');
} else if (PROD) {
  const r = JSON.parse(read(rollbackFile) || '{}');
  if (!r.edgeVersion || !r.commit) problems.push('.deploy/rollback.json is incomplete — rollback target unknown');
  else notes.push(`rollback target: edge ${r.edgeVersion} @ ${r.commit.slice(0, 8)}`);
}

// ── 6. secrets referenced but missing from the manifest ──────────────────────
const secretsManifest = join(ROOT, 'docs', 'ops', 'SECRETS.md');
if (existsSync(secretsManifest)) {
  const manifest = read(secretsManifest);
  const used = new Set(
    [...readTree(join(ROOT, 'supabase', 'functions')).matchAll(/Deno\.env\.get\('([A-Z_]+)'\)/g)]
      .map((m) => m[1]),
  );
  for (const key of used) {
    if (!manifest.includes(key)) problems.push(`secret ${key} used in code but absent from docs/ops/SECRETS.md`);
  }
}

console.log(`deploy-safety${PROD ? ' [production]' : ''}\n`);
for (const n of notes) console.log(`  ok   ${n}`);
if (problems.length) {
  console.log(`\n${problems.length} blocker(s):`);
  for (const p of problems) console.log(`  FAIL ${p}`);
  process.exit(1);
}
console.log('\nPASS — deploy is safe to promote');
