#!/usr/bin/env node
/**
 * emit-alerts.mjs — renders observability/alerts/alerts.yml FROM slo_definitions.
 *
 * Before this, alerts.yml was hand-written Prometheus YAML with no engine, free to
 * drift from the SLO table. Now the table is the source and the YAML is an artifact.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const HEADER = '# @generated by scripts/emit-alerts.mjs — do not hand-edit';
const TABLE = resolve(process.cwd(), 'supabase/slo_definitions.json');
const OUT = resolve(process.cwd(), 'observability/alerts/alerts.yml');

const defs = JSON.parse(readFileSync(TABLE, 'utf-8'));

const lines = [HEADER, '# source: supabase/slo_definitions.json (mirrors public.slo_definitions)', 'groups:', '  - name: vr-slos', '    rules:'];

for (const d of defs) {
  lines.push(`      - alert: ${d.id}`);
  lines.push(`        expr: vr_slo_burn_rate{slo="${d.id}"} >= 1`);
  lines.push(`        for: ${d.window_min}m`);
  lines.push('        labels:');
  lines.push(`          severity: ${d.severity}`);
  lines.push('        annotations:');
  lines.push(`          summary: "${d.name} is burning its error budget"`);
  lines.push(`          runbook: "${d.runbook_url}"`);
}

writeFileSync(OUT, `${lines.join('\n')}\n`, 'utf-8');
console.log(`alerts:emitted ${OUT} (${defs.length} rules)`);
